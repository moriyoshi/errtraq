export const DUCKDB_NODE_API_VERSION = "2.0.1-r.1";
/** The build-time script that bakes and then verifies the extensions; copied into the image context. */
const EXTENSION_SCRIPT = "duckdb-extensions.mjs";
export function extensionScript(): string {
  return `// Generated by errtraq build: bakes (install) or verifies (load) the DuckDB extensions.
import { DuckDBInstance } from "@duckdb/node-api";
const extensions = ${JSON.stringify(DUCKDB_EXTENSIONS)};
const load = process.argv[2] === "load";
const instance = await DuckDBInstance.create(":memory:", {
  home_directory: "/tmp/duckdb-build",
  extension_directory: ${JSON.stringify(IMAGE_EXTENSION_DIRECTORY)},
  // The verification runs under the runtime settings: nothing may reach for the network.
  ...(load
    ? { autoinstall_known_extensions: "false", autoload_known_extensions: "false" }
    : {}),
});
const connection = await instance.connect();
for (const extension of extensions)
  await connection.run(\`\${load ? "LOAD" : "INSTALL"} \${extension}\`);
console.log(process.argv[2], extensions.join(", "));
`;
}
/** Lambda base image tag (the Node major) of a runtime identifier. */
function lambdaImageTag(runtime: string): string {
  return runtime.replace(/^nodejs/, "").replace(/\.x$/, "");
}
/**
 * The container image of the AWS functions that run the DuckDB engine (D6): the Lambda Node base
 * image, the pinned native binding, and the extensions baked under `extension_directory` so a
 * function never reaches for the network (`extensionMode: "preinstalled"`, autoinstall and
 * autoload off). One image carries every image function's bundle under `<function id>/`; the
 * function's image command selects it. Extensions are installed through DuckDB itself, so they
 * always match the binding's DuckDB version and platform, then loaded once under the runtime
 * settings to fail the build rather than the first invocation.
 */
export function lambdaDockerfile(options: {
  functionIds: readonly string[];
  runtime: string;
  architecture: "arm64" | "x86_64";
}): string {
  const platform =
    options.architecture === "arm64" ? "linux/arm64" : "linux/amd64";
  return [
    `FROM --platform=${platform} public.ecr.aws/lambda/nodejs:${lambdaImageTag(options.runtime)}`,
    "# DuckDB native binding (glibc Linux build) for the archive engine; external to every bundle.",
    `RUN npm install --prefix \${LAMBDA_TASK_ROOT} --omit=dev --no-audit --no-fund --no-package-lock @duckdb/node-api@${DUCKDB_NODE_API_VERSION}`,
    "# Bake the extensions the engine LOADs; the engine never INSTALLs in this image.",
    `COPY ${EXTENSION_SCRIPT} \${LAMBDA_TASK_ROOT}/${EXTENSION_SCRIPT}`,
    `RUN mkdir -p ${IMAGE_EXTENSION_DIRECTORY} && cd \${LAMBDA_TASK_ROOT} && node ${EXTENSION_SCRIPT} install && node ${EXTENSION_SCRIPT} load && rm ${EXTENSION_SCRIPT}`,
    ...options.functionIds.map(
      (id) => `COPY ${id}/index.mjs \${LAMBDA_TASK_ROOT}/${id}/index.mjs`,
    ),
    "# No CMD: each function's image configuration sets the command (<function id>/index.handler).",
    "",
  ].join("\n");
}
export interface BuildManifest {
  stack: string;
  platform: string;
  artifacts: Record<string, BuildArtifact>;
  dockerfile?: "Dockerfile";
}
export async function buildStack(
  stack: StackConfig,
  repo: string,
  output: string,
  stackFile: string,
): Promise<BuildManifest> {
  const view = deriveDeployment(stack);
  const manifest: BuildManifest = {
    stack: stack.name,
    platform: stack.platform.manifest.id,
    artifacts: {},
  };
  if (stack.platform.manifest.id === "aws-lambda") {
    const config = stack.platform.config as {
      handler?: string;
      runtime?: string;
    };
    if (
      (config.handler ?? "index.handler") !== "index.handler" ||
      !(LAMBDA_RUNTIMES as readonly string[]).includes(
        config.runtime ?? DEFAULT_LAMBDA_RUNTIME,
      )
    )
      throw new Error(
        `Lambda build requires handler index.handler and runtime ${LAMBDA_RUNTIMES.join(" or ")}`,
      );
  }
  output = await safeDirectory(repo, output);
  const entries = await readdir(output);
  if (entries.length) {
    if (!entries.includes("manifest.json"))
      throw new Error(
        `Build output is not empty and has no build manifest: ${entries.join(", ")}`,
      );
    if ((await lstat(join(output, "manifest.json"))).isSymbolicLink())
      throw new Error("Invalid build manifest: manifest.json");
    const previous = JSON.parse(
      await readFile(join(output, "manifest.json"), "utf8"),
    ) as BuildManifest;
    if (
      previous.stack !== stack.name ||
      previous.platform !== stack.platform.manifest.id
    )
      throw new Error("Build output belongs to another stack: manifest.json");
    const previousFunctions = new Set([
      ...Object.keys(previous.artifacts ?? {}),
      ...(previous.platform === "standalone" ? ["shared"] : []),
    ]);
    if (
      entries.includes("Dockerfile") &&
      (previous.dockerfile !== "Dockerfile" ||
        (await lstat(join(output, "Dockerfile"))).isSymbolicLink())
    )
      throw new Error("Invalid generated Dockerfile");
    const unexpected = entries.filter(
      (entry) =>
        entry !== "manifest.json" &&
        entry !== "Dockerfile" &&
        entry !== EXTENSION_SCRIPT &&
        !previousFunctions.has(entry),
    );
    if (unexpected.length)
      throw new Error(
        `Build output contains files not owned by the build: ${unexpected.join(", ")}`,
      );
    for (const entry of entries.filter(
      (name) =>
        name !== "manifest.json" &&
        name !== "Dockerfile" &&
        name !== EXTENSION_SCRIPT,
    )) {
      const path = join(output, entry);
      const stat = await lstat(path);
      if (!stat.isDirectory() || stat.isSymbolicLink())
        throw new Error(`Invalid build output directory: ${entry}`);
      for (const file of await readdir(path)) {
        if (
          !["index.mjs", "meta.json", "bundle.zip", "manifest.json"].includes(
            file,
          ) ||
          (await lstat(join(path, file))).isSymbolicLink()
        )
          throw new Error(
            `Build output contains files not owned by the build: ${entry}/${file}`,
          );
      }
    }
    const current = new Set(view.functions.map((fn) => fn.id));
    for (const entry of entries)
      if (previousFunctions.has(entry) && !current.has(entry))
        await rm(join(output, entry), { recursive: true });
  }
  const conditions = (await isErrtraqWorkspace(repo)) ? ["development"] : [];
  const imageFunctions: string[] = [];
  for (const fn of view.functions) {
    let entry: string;
    let image = false;
    if (stack.platform.manifest.id === "aws-lambda") {
      const plan = deployedPlan(stack, fn.id);
      const specs = [
        ...new Set(plan.selections.map((item) => item.runtimeModule)),
      ];
      const imports = specs
        .map((spec, i) => `import * as m${i} from ${JSON.stringify(spec)};`)
        .join("\n");
      const modules = specs
        .map((spec, i) => `${JSON.stringify(spec)}:m${i}`)
        .join(",");
      const kinds = Object.fromEntries(
        plan.selections
          .filter((item) => !item.path.includes("."))
          .map((item) => [item.kind, item.path]),
      );
      const bootstrapFn = fn.roles.includes("bootstrap");
      // D6: the archive role and the archive-reading API run from the container image and import
      // the DuckDB engine and the AWS credential provider here, never in a ZIP bundle.
      image = isImageFunction(fn);
      const duckdb = image && stack.archive?.manifest.id === "archive-iceberg";
      const archiveTimeoutMs = (fn.settings.timeoutSec ?? 300) * 1000;
      const engineImport = duckdb
        ? 'import * as duckdbEngine from "@moriyoshi/errtraq-archive-iceberg/duckdb";\n'
        : "";
      const engineBindings = duckdb
        ? ',(selection)=>selection.id==="archive-iceberg"?{createEngine:duckdbEngine.create,awsCredentials:lambdaAwsCredentials(process.env)}:{}'
        : "";
      const handlerImports = bootstrapFn
        ? "awsBootstrapVault, bootstrapSecretName, createBootstrapHandler"
        : "createHandler";
      const bootstrapOptions = `{stackName:${JSON.stringify(stack.name)},store:adapters.store,kv:adapters.kv,vault:awsBootstrapVault(process.env),secretName:bootstrapSecretName(process.env),...${JSON.stringify(bootstrapRetentionPolicy(stack))},rateRejection:plan.rateRejection,logger}`;
      entry = `${imports}\n${engineImport}import { constructDeployedPlan, env, variable } from "@moriyoshi/errtraq-core/runtime";\nimport { ${handlerImports}, createSecretsManagerSource, lambdaAwsCredentials, lambdaRateLimit, retryableInitialization } from "@moriyoshi/errtraq-platform-aws-lambda/handler";\nconst plan=${sourceValue(plan)}; const modules={${modules}}; const kinds=${JSON.stringify(kinds)}; const logger={debug:(m,f)=>console.debug(m,f??{}),info:(m,f)=>console.info(m,f??{}),warn:(m,f)=>console.warn(m,f??{}),error:(m,f)=>console.error(m,f??{})};\nconst secretSource=createSecretsManagerSource({environment:process.env});
const getHandler=retryableInitialization(async()=>{ const built=await constructDeployedPlan(plan,process.env, async (name)=>{ if(!Object.hasOwn(modules,name)) throw new Error("Unknown module "+name); return modules[name]; }, logger, secretSource${engineBindings}); try { const adapters=Object.fromEntries(Object.entries(kinds).map(([kind,path])=>[kind,built.instances.get(path)])); return ${bootstrapFn ? `createBootstrapHandler(${bootstrapOptions})` : `createHandler({roles:${JSON.stringify(fn.roles)},http:${JSON.stringify(fn.http)},recordMode:plan.recordMode,rateRejection:plan.rateRejection,rateLimit:lambdaRateLimit(process.env.ERRTRAQ_INGEST_RATE_LIMIT),archiveRetentionDays:plan.archiveRetentionDays,archiveInvocationTimeoutMs:${archiveTimeoutMs},adapters,logger})`}; } catch(error) { try { await built.close(); } catch(cleanup) { throw new AggregateError([error,cleanup],"Handler creation and cleanup failed"); } throw error; } });\nexport async function handler(event){return (await getHandler())(event);}\n`;
    } else if (stack.platform.manifest.id === "standalone") {
      const localImport = (path: string) => {
        const location = relative(repo, path).split(sep).join("/");
        return location.startsWith("./") || location.startsWith("../")
          ? location
          : `./${location}`;
      };
      const specs = [
        ...new Set(
          [...selections(stack).values()].map(
            (selection) => selection.runtimeModule,
          ),
        ),
      ];
      const imports = specs
        .map(
          (spec, index) =>
            `import * as m${index} from ${JSON.stringify(spec)};`,
        )
        .join("\n");
      const modules = specs
        .map((spec, index) => `${JSON.stringify(spec)}:m${index}`)
        .join(",");
      // The DuckDB engine is imported statically, and only for an archive-iceberg stack; its
      // native binding stays external to the bundle and is installed in the image (D6).
      const duckdb = stack.archive?.manifest.id === "archive-iceberg";
      entry = `${imports}${duckdb ? '\nimport * as duckdbEngine from "@moriyoshi/errtraq-archive-iceberg/duckdb";' : ""}\nimport stack from ${JSON.stringify(localImport(stackFile))};\nimport {constructStack,devToken,dsnOrigin} from "@moriyoshi/errtraq-cli/standalone-entry";\nconst modules={${modules}};\nconst built=await constructStack(stack,${JSON.stringify(fn.roles)},process.env,async(name)=>{if(!Object.hasOwn(modules,name)) throw new Error("Unknown module "+name); return modules[name];}${duckdb ? ',(selection)=>selection.manifest.id==="archive-iceberg"?{createEngine:duckdbEngine.create}:{}' : ""});\nconst project=await built.platform.prepare(false,devToken); const server=await built.platform.start();\nconst destination=dsnOrigin(server.host,server.port,server.publicUrl); if(destination.fallback) console.log("Note: DSN uses localhost; use your public host for remote clients."); const dsn=new URL(destination.origin); dsn.username=project.publicKey; dsn.pathname="/"+project.projectId; console.log("DSN: "+dsn.toString()); console.log("API token: "+project.token); console.log("Listening: http://"+server.host+":"+server.port);\nlet stopping=false;
for(const signal of ["SIGTERM","SIGINT"]) process.on(signal,()=>{if(stopping){if(process.pid===1) process.exit(signal==="SIGTERM"?143:130); process.removeAllListeners(signal); process.kill(process.pid,signal); return;} stopping=true; void server.close().then(()=>built.close()).catch((error)=>{console.error(error);process.exitCode=1;});});`;
    } else
      throw new Error(
        `Build is not supported for platform ${stack.platform.manifest.id}`,
      );
    const esbuildTarget =
      stack.platform.manifest.id === "aws-lambda"
        ? lambdaEsbuildTarget(
            ((stack.platform.config as { runtime?: string }).runtime ??
              DEFAULT_LAMBDA_RUNTIME) as LambdaRuntime,
          )
        : "node22";
    const result = await build({
      stdin: {
        contents: entry,
        resolveDir: repo,
        sourcefile: `entry-${fn.id}.ts`,
        loader: "ts",
      },
      bundle: true,
      external:
        stack.archive?.manifest.id === "archive-iceberg" ? ["@duckdb/*"] : [],
      platform: "node",
      format: "esm",
      // CommonJS dependencies (pg) call require() for Node builtins; an ESM bundle has no
      // require, so esbuild's shim throws "Dynamic require of ... is not supported" at load.
      banner: {
        js: 'import{createRequire as __errtraqCreateRequire}from"node:module";const require=__errtraqCreateRequire(import.meta.url);',
      },
      target: esbuildTarget,
      minify: stack.platform.manifest.id === "aws-lambda",
      keepNames: true,
      conditions,
      write: false,
      metafile: true,
      outfile: "index.mjs",
      logLevel: "silent",
    });
    const file = result.outputFiles[0];
    if (!file) throw new Error("esbuild did not produce a bundle");
    const meta = result.metafile;
    const inputPaths = Object.entries(meta.inputs).flatMap(([path, input]) => [
      path,
      ...input.imports.flatMap((item) => [item.path, item.original ?? ""]),
    ]);
    if (
      inputPaths.some((path) => isAbsolute(path)) ||
      [repo, homedir()].some((path) => containsLocalPath(file.text, path))
    )
      throw new Error("Build output contains an absolute repository path");
    const directory = join(output, fn.id);
    await mkdir(directory, { recursive: true });
    await writeFile(join(directory, "index.mjs"), file.contents);
    await writeFile(
      join(directory, "meta.json"),
      `${JSON.stringify(result.metafile, null, 2)}\n`,
    );
    if (stack.platform.manifest.id === "aws-lambda" && image) {
      imageFunctions.push(fn.id);
      // The bundle ships inside the image, not as a ZIP; a leftover ZIP from an earlier build of
      // this function as a ZIP function would only mislead.
      await rm(join(directory, "bundle.zip"), { force: true });
      const platformConfig = stack.platform.config as {
        handler?: string;
        runtime?: string;
      };
      manifest.artifacts[fn.id] = {
        path: relative(repo, join(directory, "index.mjs")).split(sep).join("/"),
        handler: platformConfig.handler ?? "index.handler",
        runtime: platformConfig.runtime ?? DEFAULT_LAMBDA_RUNTIME,
        contentHash: createHash("sha256")
          .update(file.contents)
          .digest("base64"),
        packaging: "image",
      };
      await writeFile(
        join(directory, "manifest.json"),
        `${JSON.stringify(manifest.artifacts[fn.id], null, 2)}\n`,
      );
    } else if (stack.platform.manifest.id === "aws-lambda") {
      const bytes = zipSync(
        {
          "index.mjs": [
            strToU8(file.text),
            { mtime: new Date(2000, 0, 1, 0, 0, 0) },
          ],
        },
        { level: 6 },
      );
      const artifactPath = join(directory, "bundle.zip");
      await writeFile(artifactPath, bytes);
      const platformConfig = stack.platform.config as {
        handler?: string;
        runtime?: string;
      };
      manifest.artifacts[fn.id] = {
        path: relative(repo, artifactPath).split(sep).join("/"),
        handler: platformConfig.handler ?? "index.handler",
        runtime: platformConfig.runtime ?? DEFAULT_LAMBDA_RUNTIME,
        contentHash: createHash("sha256").update(bytes).digest("base64"),
      };
      await writeFile(
        join(directory, "manifest.json"),
        `${JSON.stringify(manifest.artifacts[fn.id], null, 2)}\n`,
      );
    }
  }
  if (stack.platform.manifest.id === "aws-lambda") {
    const dockerfile = join(output, "Dockerfile");
    if (imageFunctions.length) {
      const config = stack.platform.config as {
        runtime?: string;
        imageArchitecture?: "arm64" | "x86_64";
      };
      await rm(dockerfile, { force: true });
      await writeFile(
        dockerfile,
        lambdaDockerfile({
          functionIds: imageFunctions,
          runtime: config.runtime ?? DEFAULT_LAMBDA_RUNTIME,
          architecture: config.imageArchitecture ?? "arm64",
        }),
      );
      await rm(join(output, EXTENSION_SCRIPT), { force: true });
      await writeFile(join(output, EXTENSION_SCRIPT), extensionScript());
      manifest.dockerfile = "Dockerfile";
    } else {
      await rm(dockerfile, { force: true });
      await rm(join(output, EXTENSION_SCRIPT), { force: true });
    }
  }
  if (stack.platform.manifest.id === "standalone") {
    const id = view.functions[0]?.id;
    if (!id || view.functions.length !== 1)
      throw new Error("Standalone requires one function");
    // D6: an archive-iceberg stack runs the whole pipeline in this one process, so the image
    // carries the DuckDB native binding (external to the bundle). The `iceberg` and `httpfs`
    // extensions are installed by DuckDB at first start (engine.extensionMode runtime-install,
    // needs egress); baking them is the AWS image recipe (TODO(M4i)).
    const duckdbLayer =
      stack.archive?.manifest.id === "archive-iceberg"
        ? `# DuckDB native binding for the archive engine (external to the bundle).\nRUN npm install --prefix /app --omit=dev --no-audit --no-fund --no-package-lock @duckdb/node-api@${DUCKDB_NODE_API_VERSION} && chown -R node:node /app\n`
        : "";
    const dockerfile = `FROM node:22.23-bookworm-slim\nWORKDIR /app\nRUN mkdir -p /data && chown node:node /data\n${duckdbLayer}COPY --chown=node:node ${id}/index.mjs /app/index.mjs\n# Explicitly opt in to listening on the container network.\nENV ERRTRAQ_HOST=0.0.0.0 ERRTRAQ_DATA_DIR=/data\nUSER node\nVOLUME ["/data"]\nEXPOSE 8787\nHEALTHCHECK --interval=30s --timeout=3s --start-period=10s --retries=3 CMD node -e "fetch('http://127.0.0.1:'+(process.env.ERRTRAQ_PORT||'8787')+'/health').then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))"\nENTRYPOINT ["node", "/app/index.mjs"]\n`;
    await writeFile(join(output, "Dockerfile"), dockerfile);
    manifest.dockerfile = "Dockerfile";
  }
  await writeFile(
    join(output, "manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );
  return manifest;
}

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * The run stack of the first real GCP verification (G8 run 1), derived from the repository's
 * `stacks/gcp-firestore.ts` and written into the git-ignored `.agents-workspace/tmp/g8/`.
 * Nothing environment specific is written: the project, region and operator member are read from
 * the environment when the stack is loaded (`stacks/gcp-env.ts`), exactly like the example stacks.
 *
 * Differences from `stacks/gcp-firestore-bootstrap.ts`: the `record` role and grouped recording
 * (so the ordered `record` queue is exercised), `protection: "disposable"` (teardown must work),
 * the bootstrap role, and optionally `ingress = internal` on the push and Scheduler callees.
 */
export function renderRunStack(options) {
  const {
    ingressInternal = false,
    rateLimit,
    bootstrapSecretName = "errtraq-bootstrap-gcp-g8",
    stackName = "gcp-g8",
  } = options;
  if (!/^[a-z][a-z0-9-]{1,18}[a-z0-9]$/.test(stackName))
    throw new Error(
      "The stack name must be 3 to 20 lowercase letters, digits or hyphens",
    );
  if (!/^[A-Za-z0-9_-]{1,255}$/.test(bootstrapSecretName))
    throw new Error("Invalid bootstrap secret name");
  if (
    rateLimit !== undefined &&
    rateLimit !== null &&
    !(Number.isSafeInteger(rateLimit) && rateLimit > 0)
  )
    throw new Error("rateLimit must be a positive integer or null");
  const settings = ingressInternal
    ? `\n    settings: {\n      consumer: { ingress: "internal" },\n      record: { ingress: "internal" },\n      cron: { ingress: "internal" },\n    },`
    : "";
  const limit =
    rateLimit === undefined
      ? ""
      : `\n    rateLimit: ${rateLimit === null ? "null" : rateLimit},`;
  return `// Generated by scripts/gcp-verify/stack.mjs for G8 run 1; do not commit.
import { defineStack, output, variable } from "@moriyoshi/errtraq-core";
import { cloudRun } from "@moriyoshi/errtraq-platform-cloud-run/stack";
import { IMAGE_VARIABLE, requiredEnv } from "./gcp-env.ts";
import base from "./gcp-firestore.ts";

const projectId = requiredEnv("ERRTRAQ_GCP_PROJECT");
const region = requiredEnv("ERRTRAQ_GCP_REGION");
const operator = requiredEnv("ERRTRAQ_GCP_OPERATOR_MEMBER");

export default defineStack({
  ...(Object.fromEntries(Object.entries(base)) as typeof base),
  name: ${JSON.stringify(stackName)},
  protection: "disposable",
  recordMode: "grouped",
  platform: cloudRun({
    projectId,
    region,
    image: variable(IMAGE_VARIABLE),
    roles: ["ingest", "api", "consumer", "record", "cron", "bootstrap"],
    split: ["ingest", "api", "consumer", "record", "cron", "bootstrap"],${limit}${settings}
    bootstrapSecretName: ${JSON.stringify(bootstrapSecretName)},
    operatorMembers: [operator],
  }),
  outputs: {
    ingest_url: output("platform", "ingest_url"),
    api_url: output("platform", "api_url"),
    bootstrap_url: output("platform", "bootstrap_url"),
  },
});
`;
}

/**
 * Write the run stack to `<directory>/stack.ts`; `directory` must live inside the repository so
 * the workspace packages resolve. Copies of the two example files it imports sit beside it (the
 * example text stays the single source).
 */
export async function writeRunStack(repo, directory, options = {}) {
  const target = resolve(directory);
  await mkdir(target, { recursive: true });
  for (const name of ["gcp-env.ts", "gcp-firestore.ts"]) {
    const text = await readFile(resolve(repo, "stacks", name), "utf8");
    await writeFile(resolve(target, name), text);
  }
  const file = resolve(target, "stack.ts");
  await writeFile(file, renderRunStack(options));
  return file;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const args = process.argv.slice(2);
  const flag = (name) => {
    const index = args.indexOf(name);
    return index < 0 ? undefined : args[index + 1];
  };
  const repo = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
  const out = flag("--out") ?? resolve(repo, ".agents-workspace/tmp/g8");
  const rate = flag("--rate-limit");
  const file = await writeRunStack(repo, out, {
    ingressInternal: args.includes("--ingress-internal"),
    ...(rate === undefined
      ? {}
      : { rateLimit: rate === "disabled" ? null : Number(rate) }),
    ...(flag("--stack-name") ? { stackName: flag("--stack-name") } : {}),
    ...(flag("--secret-name")
      ? { bootstrapSecretName: flag("--secret-name") }
      : {}),
  });
  console.log(`Wrote ${relative(repo, file)}`);
}
